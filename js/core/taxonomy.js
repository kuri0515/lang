// =====================================================================
// 標籤分類與教學順序
//
// 為什麼獨立成一個模組：這是教學知識，不是畫面細節。
// 瀏覽的篩選列、之後的發音課程路徑都要用同一份，抄兩份必然漂移。
//
// 【為什麼要分組】
//   94 個標籤裡混著兩種性質完全不同的東西：
//     主題（食物·動物·場所）  學習者按興趣挑 —— 當篩選器是對的
//     發音（收音ㄷ·激音化）    這是一套有順序的課程 —— 當篩選器是錯的
//   平鋪在一起，想找「食物」得滑過「收音ㄼ」。
//
// 【為什麼發音不按數量排】
//   收音ㄽ 只掛 1 條，按數量排會落到最末，看起來像殘渣。
//   但它是「複合收音」這一課裡的一行，不是一個冷門分類。
//   自學者沒有老師說「你該練複合收音了」，順序本身就是教學。
//   所以發音一律按下面的序列排，與條目數無關。
// =====================================================================

/**
 * 發音教學序列。
 *
 * 【給台灣學習者的兩件事】
 *   好消息：台語有入聲 -p/-t/-k，與韓語的 ㅂ/ㄷ/ㄱ 收音同樣是「舌位到定點就停、
 *   不放氣」。只會華語的人得從頭練這個（華語只有 -n/-ng 兩種鼻音收尾），
 *   會台語的人等於先天有底子 —— 這是台灣學習者相對優勢最大的一塊。
 *   壞消息：韓語的平音／激音／硬音是三分對立（ㄱ／ㅋ／ㄲ），
 *   華語只有送氣與不送氣兩分，硬音 ㄲㄸㅃㅆㅉ 沒有對應，最難聽出也最難發。
 *
 * 【順序為什麼是這樣】
 *   ★ 連音必須排在複合收音之前 —— 這是我一開始排錯的地方。
 *     複合收音的規則講不通，除非先懂連音：넓다 讀 [널따]（子音前只留 ㄹ），
 *     但 넓어요 讀 [널버요]（遇母音時 ㅂ 移到下一音節復活）。
 *     沒學連音就看這組規則，只會覺得毫無道理、被迫死背。
 *   音變規則的內部順序照使用頻率與依賴關係：
 *     硬音化最常撞見（학교＝[학꾜]）→ 鼻音化 → 流音化 → 激音化 →
 *     顎化最少見且只出現在特定詞尾，放最後。
 */
export const PRON_ORDER = [
  // ① 基本收音七個。韓語所有收音最終都歸到這七個音
  '收音ㄱ', '收音ㄴ', '收音ㄷ', '收音ㄹ', '收音ㅁ', '收音ㅂ', '收音ㅇ',
  // ② 連音 —— 提到複合收音之前，否則下一組的規則講不通
  '連音練習',
  // ③ 複合收音：兩個子音只讀一個，且遇母音會拆開
  '收音ㄳ', '收音ㄵ', '收音ㄶ', '收音ㄺ', '收音ㄻ', '收音ㄼ',
  '收音ㄽ', '收音ㄾ', '收音ㄿ', '收音ㅀ', '收音ㅄ',
  // ④ 音變規則，依撞見頻率排
  '硬音化', '鼻音化', '流音化', '激音化', '顎化',
  // ⑤ 特殊母音
  '의的發音',
];

/**
 * 主題組裡優先露出的「起步主題」。
 *
 * 主題其餘按條目數排（多的先看到），但食物有 80 條會排第一 ——
 * 對剛起步的自學者，先背 80 個食物名詞不如先會打招呼跟自我介紹。
 * 自學者沒有老師說「先學這個」，順序就是唯一的指引。
 */
export const STARTER_TOPICS = ['問候', '自我介紹', '基礎', '回應'];

/** 語法類：詞性與句子結構 */
export const GRAMMAR_TAGS = [
  '句型', '動詞', '形容', '副詞', '量詞', '疑問詞', '時態', '敬語', '俗諺',
];

const PRON_SET = new Set(PRON_ORDER);
const GRAM_SET = new Set(GRAMMAR_TAGS);

export const GROUPS = [
  { key: 'topic', label: '主題', hint: '前幾個是起步優先，其餘按興趣挑' },
  { key: 'pron', label: '發音', hint: '依教學順序排列，從上往下' },
  { key: 'grammar', label: '語法', hint: '詞性與句型' },
];

/**
 * 把 listTags() 的 [[tag, count]] 分成三組。
 *
 * 未列進 PRON_ORDER 的 收音* 標籤也算發音組 —— 日後新增
 * 收音ㅆ 之類時不會憑空掉出分組，只是排在該組最後。
 * 硬名單漏掉一項就讓標籤消失，是這種設計最容易犯的錯。
 */
export function groupTags(pairs) {
  const out = { topic: [], pron: [], grammar: [] };
  for (const [tag, n] of pairs) {
    if (PRON_SET.has(tag) || tag.startsWith('收音')) out.pron.push([tag, n]);
    else if (GRAM_SET.has(tag)) out.grammar.push([tag, n]);
    else out.topic.push([tag, n]);
  }
  // 主題：起步主題置頂，其餘按數量；語法按數量；發音按教學順序
  const starter = (t) => (STARTER_TOPICS.indexOf(t) + 1 || 999);
  out.topic.sort((a, b) => starter(a[0]) - starter(b[0]) || b[1] - a[1]);
  out.grammar.sort((a, b) => b[1] - a[1]);
  const rank = (t) => (PRON_ORDER.indexOf(t) + 1 || 999);
  out.pron.sort((a, b) => rank(a[0]) - rank(b[0]) || a[0].localeCompare(b[0]));
  return out;
}

/**
 * 掌握門檻。要求 100% 會讓人卡在某一課出不去 —— 一課裡有幾條特別難是常態，
 * 為了那兩條擋住整條路線，自學者只會放棄。低於 80% 又太鬆，一路夾生。
 */
export const LESSON_DONE = 0.8;

/**
 * 從課程進度算出「下一課」。
 *
 * ★ 判準是「還沒掌握牢」而不是「還沒碰過」——
 *   碰過兩條就算過關、直接跳下一課，等於整條路線一路夾生，
 *   而發音正是最不能夾生的部分：底子沒打穩，後面每個音變規則都聽不懂。
 *
 * rows = [{ tag, total, started, mastered }]，順序不拘，本函式自己照教學序排。
 * 回傳 { next, done, total }；全部達標時 next 為 null。
 */
export function nextLesson(rows) {
  const ordered = PRON_ORDER
    .map((t) => rows.find((r) => r.tag === t))
    .filter((r) => r && r.total > 0);
  const rate = (r) => r.mastered / r.total;
  return {
    next: ordered.find((r) => rate(r) < LESSON_DONE) ?? null,
    done: ordered.filter((r) => rate(r) >= LESSON_DONE).length,
    total: ordered.length,
    ordered,
  };
}

