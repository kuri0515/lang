/**
 * 一課練完的收尾話。
 *
 * 【刻意不是每課都有】
 *   每課都給一句，等於每句都不算數 —— 稱讚天天有就成了背景音。
 *   只有真的有話可說的課才給：華語沒有的音、後面全靠它的地基、
 *   進度本來就會慢的那幾課。其餘留白，讓成績自己說話。
 *
 * 【答得不好時不假稱讚】
 *   自學者答錯一半，最不需要的是「太棒了」。
 *   要的是有人告訴他「這裡卡住是正常的，原因是這個」——
 *   把挫敗重新定義成預期中的一步，他才留得下來。
 */
const OUTRO_OK = {
  '收音ㄹ': '華語沒有的音，你拿下了。後面的收音會輕鬆。',
  '連音練習': '地基打好了，後面的規則都建在這上面。',
  '硬音化': '你開始用耳朵聽了，不是靠拼音。',
  '의的發音': '發音課到這收尾。再聽一次韓劇試試。',
};
const OUTRO_LOW = {
  '收音ㄹ': '華語沒這個音，不順很正常。嘴巴需要時間。',
  '硬音化': '這課靠耳朵，拼音幫不上忙，慢是正常的。',
};
/** 複合收音十一課共用 —— 它們是同一條規則的十一個實例，話也該是同一句 */
const OUTRO_COMPLEX_OK = '最硬的一段過了，後面順。';
const OUTRO_COMPLEX_LOW = '這段最難，一次記不住正常。記規則就好：只唸一個，遇母音拆開。';

// 基本七收音以外的 收音* 就是複合收音。
// 不能用字串長度判斷 —— 收音ㄼ 與 收音ㄱ 都是三個字，長度分不出來。
const BASIC_FINALS = new Set(
  ['收音ㄱ', '收音ㄴ', '收音ㄷ', '收音ㄹ', '收音ㅁ', '收音ㅂ', '收音ㅇ']);
const isComplex = (t) => t.startsWith('收音') && !BASIC_FINALS.has(t);

/**
 * @param {string} tag       課程標籤，非課程內容傳空字串
 * @param {number} accuracy  本輪正確率 0–1
 * @returns {string} 收尾話；沒有話可說時回空字串
 */
export function lessonOutro(tag, accuracy) {
  if (!tag || !LESSON_INTRO[tag]) return '';
  const low = accuracy < 0.6;
  if (isComplex(tag)) return low ? OUTRO_COMPLEX_LOW : OUTRO_COMPLEX_OK;
  return (low ? OUTRO_LOW[tag] : OUTRO_OK[tag]) || '';
}

