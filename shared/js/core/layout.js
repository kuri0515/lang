// =====================================================================
// 列表版式：哪些條目的中文要換到自己的一行
//
// 【為什麼要分】
//   單字「고맙습니다 — 謝謝」一行就夠，而且詞庫有上千條，
//   全部拆成兩行會把列表拉長一倍。句子不同：韓文本身就占滿一行，
//   後面再接「— 中文」，中文會被擠到下一行、斷在半句中間
//   （實際看到的是一行只剩「麼細節。」三個字）。
//
// 【為什麼只寫一份】
//   詞庫頁、單詞進度、學習記錄、回顧清單四處都有「韓文＋中文」的列，
//   各自判斷「長不長」，遲早漂移成一處換行、一處不換。
// =====================================================================
import { stripRuby } from './ruby.js';

/** 句子一律換行；詞與詞組在韓文超過 14 個字時也換（太長一行放不下中文） */
export function isLongItem(item) {
  if (!item) return false;
  if (item.item_type === 'sentence') return true;
  return stripRuby(String(item.ko || '')).length > 14;
}
