-- =====================================================================
-- 0017_study_prefs — 練習方式的偏好（題型／方向／內容類型）
--
-- 【要解決的事】
--   使用者把方向設成「中→韓」，下次打開又跳回「韓→中」。
--   那個設定每次都要重設，而它正是最影響體感的一個 ——
--   看中文想外語（產出）與看外語想中文（辨識）是兩種完全不同的練習。
--
-- 【為什麼用 jsonb 而不是逐一開欄位】
--   profiles 已經有一個 study_mode 欄位，但它從來沒有被套用或儲存過 ——
--   開了欄位、沒有接上，就是一個永遠對不上實際狀態的假資料。
--
--   而練習方式這一組還會長：今天剛加了「拼出來」，明天可能加別的。
--   每加一個設定就一次 migration，久了沒有人想動它。
--   jsonb 讓「加一個設定」不必動 schema —— 代價是資料庫不幫忙驗證，
--   所以前端讀取時一定要能容忍缺欄位與壞值（見 views/home.js 的 applyPrefs）。
--
-- 【為什麼不塞進 localStorage 就好】
--   換一台裝置登入就沒了。而這是「我習慣怎麼練」，不是「我做到哪」——
--   前者跟著人走，後者跟著裝置走也無所謂。
--
-- 【舊的 study_mode 欄位】
--   留著不動。它沒有被任何程式讀寫，刪掉要另外確認沒有其他依賴，
--   而那不是這次的範圍。新的東西一律走 study_prefs。
-- =====================================================================

alter table public.profiles
  add column if not exists study_prefs jsonb not null default '{}'::jsonb;

comment on column public.profiles.study_prefs is
  '練習方式偏好：{ mode, dir, type }。用 jsonb 是因為這一組還會長，'
  '每加一個設定就一次 migration 的話沒有人想動它。前端必須容忍缺欄位與壞值。';
