-- 0026_episode_deck — 一集的詞屬於哪一副詞庫
--
-- 【要解決的事】
--   「這一幕的詞」是拿斷詞結果（原形）去 items 裡查卡片的，
--   而查的時候沒有限定詞庫。同一個詞形在兩副詞庫裡都有的話，
--   兩張卡都會被撈進來 ——
--   於是這一幕的清單裡混進了五十音課本的卡片，
--   「練這一幕（N）」的數字被灌水，練到的是不屬於這一幕的東西。
--
--   實測：日文站有 7 個詞形同時存在 kana-01 與 spy-s1，
--   影響 29/70 幕。而畫面看起來完全正常 —— 那些詞確實出現在這一幕，
--   只是被連到了另一副詞庫的卡片。
--
-- 【為什麼記在集上，不是靠命名規則猜】
--   靠 work 前綴去猜詞庫代號（spy → spy-s1）會在第二季就壞掉，
--   而壞掉的方式是「查不到卡片」，不是報錯。
--   讓資料自己說出來，比讓程式猜可靠。
-- =====================================================================

alter table public.script_episodes
  add column if not exists deck_slug text;

comment on column public.script_episodes.deck_slug is
  '這一集的詞建在哪一副詞庫。查「這一幕的詞」時要用它限定範圍 —— '
  '不限定的話，同一個詞形在別副詞庫裡的卡片也會被撈進來，'
  '而畫面看起來完全正常。';
