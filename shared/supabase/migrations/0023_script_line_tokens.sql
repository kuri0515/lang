-- =====================================================================
-- 0023_script_line_tokens — 每一行的詞（原形）
--
-- 【要解決的事】
--   精讀畫面要顯示「這一幕出現了哪些詞」，並連到對應的單字卡。
--
-- 【為什麼不在前端用字串比對算出來】
--   比對「這一行有沒有包含這個詞」會誤中：
--   「気」會在「元気」「気持ち」裡命中，「手」會在「相手」「手続き」裡命中，
--   而日文沒有詞界空白，這種誤中沒有辦法用邊界規則排除。
--   結果是一幕的詞表混進一堆根本沒出現的詞 —— 而它看起來很合理，
--   使用者不會發現，只會覺得「這個詞我怎麼沒讀到」。
--
--   斷詞在抽取階段本來就做了（Sudachi），把結果存下來就是精確的。
--   前端不必再猜，也不必載入整副詞庫來比對。
-- =====================================================================

alter table public.script_lines
  add column if not exists tokens text[] not null default '{}';

comment on column public.script_lines.tokens is
  '這一行出現的詞（原形），抽取時由 Sudachi 斷出。'
  '存下來而不是前端字串比對：日文沒有詞界，「気」會在「元気」裡誤中，'
  '而那種錯看起來很合理，使用者不會發現。';

create index if not exists script_lines_tokens_idx
  on public.script_lines using gin (tokens);
