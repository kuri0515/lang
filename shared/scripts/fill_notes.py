def req(url,key,method,path,body=None):
    data=json.dumps(body,ensure_ascii=False).encode() if body is not None else None
    r=urllib.request.Request(f"{url}/rest/v1/{urllib.parse.quote(path,safe='?&=,.()*')}",
                             data=data,method=method)
    for h,v in [("apikey",key),("Authorization",f"Bearer {key}"),
                ("Content-Type","application/json"),("Prefer","return=representation")]:
        r.add_header(h,v)
    with urllib.request.urlopen(r) as resp:
        return json.loads(resp.read().decode() or "[]")

def fetch(url,key):
    rows=[]
    while True:
        p=req(url,key,"GET","items?select=id,ko,zh,note,item_type&is_active=eq.true"
                            f"&offset={len(rows)}&limit=1000")
        rows+=p
        if len(p)<1000: return rows

def main():
    ap=argparse.ArgumentParser(); ap.add_argument("--apply",action="store_true")
    a=ap.parse_args()
    url,key=load_env()
    items=fetch(url,key)
    miss=[r for r in items if not r.get("note")]
    print(f"缺 note {len(miss)} 條，判定表 {len(NOTES)} 條")
    unknown=[k for k in NOTES if not any(r["ko"]==k for r in items)]
    if unknown: sys.exit(f"❌ 不在資料庫：{unknown}")
    targets=[(r,NOTES[r["ko"]]) for r in miss if r["ko"] in NOTES]
    left=[r["ko"] for r in miss if r["ko"] not in NOTES]
    print(f"將寫入 {len(targets)} 筆")
    print(f"刻意不寫的 {len(left)} 條（沒有辨析／發音／詞源可寫，硬湊只會稀釋真正的提醒）：")
    print("   " + "、".join(left))
    if not a.apply:
        print("\n🔎 dry-run：什麼都沒寫。加 --apply 生效。"); return
    for r,n in targets:
        req(url,key,"PATCH",f"items?id=eq.{r['id']}",{"note":n})
    after={x["id"]:x for x in fetch(url,key)}
    bad=[r["ko"] for r,n in targets if after[r["id"]].get("note")!=n]
    if bad: sys.exit(f"❌ {len(bad)} 筆回讀不符：{bad}")
    print(f"✅ {len(targets)} 筆全部回讀相符")

if __name__=="__main__": main()
