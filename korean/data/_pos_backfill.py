# -*- coding: utf-8 -*-
"""韓文站漏標詞性的 29 條 —— 幾乎全是詞組與句型。

【為什麼會漏這 29 條】
    原本的詞性表是為「單字」設計的（명사／동사／형용사…），
    而這 29 條是詞組（장바구니에 담다）、句型（-잖아요）與慣用表現（실화냐）。
    它們沒有單一詞性可填，於是就一直空著 ——
    不會報錯，只是四選一時配不到同類的干擾項。

【新增的四類，都是為了干擾項的品質】
    어미      句尾語尾（-잖아요、-거든요…）。這幾個是同一組概念，
              互為干擾項才是真的在練「這句該用哪個語尾」。
              拿名詞當干擾項等於送分。
    명사구    名詞性的詞組（첫 페이지、품절 임박）
    동사구    動詞性的詞組（입어 보다、챙겨 먹다）
    형용사구  形容詞性的詞組。目前只有 운이 좋다 一條 ——
              一個成員的類別對干擾項沒有幫助，但標對比標錯好：
              韓語的 좋다 是形容詞不是動詞，混進 동사구 會教錯。
    표현      成句的慣用表現與縮寫語（할많하않、이불 밖은 위험해）

【為什麼 -는 법 歸명사구而不是어미】
    법 是依存名詞，「-는 법」整個是名詞性的（…的方法）。
    看起來像句型，但它在句中的位置與名詞一樣。
"""

POS = {
    # ── 句尾語尾：這一組要互為干擾項才有練習價值 ──────────────
    '-잖아요': '어미',
    '-거든요': '어미',
    '-더라고요': '어미',
    '-네요': '어미',
    '-죠': '어미',
    '-는데요': '어미',

    # ── 名詞性詞組 ────────────────────────────────────
    '어려운 시기': '명사구',
    '품절 임박': '명사구',
    '첫 페이지': '명사구',
    '-는 법': '명사구',      # 법 是依存名詞，整個詞組是名詞性的

    # ── 動詞性詞組 ────────────────────────────────────
    '입어 보다': '동사구',
    '장바구니에 담다': '동사구',
    '혼자 보내다': '동사구',
    '안 나가다': '동사구',
    '챙겨 먹다': '동사구',

    # ── 形容詞性詞組 ───────────────────────────────────
    '운이 좋다': '형용사구',   # 좋다 在韓語是形容詞，不是動詞

    # ── 慣用表現・縮寫語・網路用語 ──────────────────────────
    '얼마예요?': '표현',
    '꽃길만 걷자!': '표현',
    '이불 밖은 위험해': '표현',
    '나 자신이 죽도록 싫다': '표현',
    '맛있으면 0칼로리': '표현',
    '다이어트는 내일부터': '표현',
    '할많하않': '표현',        # 할 말은 많지만 하지 않겠다 的縮寫
    '낄끼빠빠': '표현',        # 낄 때 끼고 빠질 때 빠져라 的縮寫
    '두말하면 잔소리죠.': '표현',
    '실화냐': '표현',
    '그치?': '표현',
    '뭐랄까': '표현',
    '아 맞다': '표현',
}

# 這一站已經在用的詞性，加上這次新增的四類。
# 打錯字不會報錯，只會讓那個詞永遠配不到同類的干擾項，所以要有白名單。
VALID = {'명사', '동사', '형용사', '수사', '부사', '인사말', '의존명사',
         '대명사', '감탄사', '어미', '명사구', '동사구', '형용사구', '표현'}

assert set(POS.values()) <= VALID, set(POS.values()) - VALID
