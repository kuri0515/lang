// =====================================================================
// 日語課程內容
//
// 這裡只有「教什麼」，沒有「怎麼算」——
// 分組、排序、下一課、掌握門檻的邏輯全在 shared/js/core/taxonomy.js，
// 與韓文站共用同一套引擎。
//
// 【給台灣學習者的兩件事】
//   好消息：漢字已經會了，這是華語圈學日語最大的先天優勢 ——
//   看到「世界」「時間」「注意」直接懂意思，起步比歐美學習者快得多。
//   而且音讀常和台語很近（世界 せかい／台語 sè-kài、世間 せけん／sè-kan），
//   因為兩者都保留了中古漢語的音韻層。會台語的人猜音讀命中率明顯較高。
//
//   壞消息：日語靠「拍」（モーラ）計時，每一拍等長 ——
//   長音、促音、撥音各自佔一整拍，但它們都不是一個完整音節。
//   華語沒有這個概念，所以 おばさん（阿姨）和 おばあさん（奶奶）
//   在台灣學習者耳裡常常一樣。這是日語發音最大的一道坎，不是小細節。
//   另一個坎是高低重音：華語的聲調在「字」上，日語的高低在「詞」上，
//   橋（はし↗）和箸（はし↘）不是兩個音，是同一串音的兩種走勢。
//
// 【順序為什麼是這樣】
//   ★ 長音 → 促音 → 撥音 必須連著排，而且排在高低重音之前。
//     這三課看起來是三件事，其實是同一件事的三個樣子：
//     「一個不成音節、卻要佔滿一整拍的東西」。分開教，學習者會覺得
//     是三條要死背的規則；連著教，第三課時他自己就會說「又是這個」。
//     而高低重音是疊在拍子上的 —— 拍子沒數對，重音無從談起。
//   濁音・半濁音要在連濁之前 —— 連濁就是「複合詞時前清變後濁」，
//   不先認得濁音符號，這課根本沒東西可講。
//   母音無聲化放最後：不學也聽得懂、說得通，只是會少一分自然。
//   排最後不是因為不重要，是因為它是「已經會說之後的打磨」。
// =====================================================================

