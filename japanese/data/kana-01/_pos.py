# -*- coding: utf-8 -*-
"""詞性（pos）。

【為什麼要有】
    四選一挑干擾項時，同詞性的選項會加分（shared/js/study/modes/choice.js）。
    沒有詞性時，同一課裡名詞和動詞混著當選項 ——
    看到「たのしい（快樂的）」而選項裡三個都是名詞，不必真的認得就能刪掉。
    練了很多次，沒練到會錯的那一下。

【★ 絕對不能從中文釋義推】
    這是整份檔案存在的理由。中文與日文的詞性根本不對應：

        ダンス   跳舞      → 中文像動詞，日語是名詞
        さんぽ   散步      → 同上
        メンズ   男性（用）的 → 中文像形容詞，日語是名詞
        ヤング   年輕的     → 同上
        ほんとう 真的      → 同上

    反過來也一樣：「偷」對應的 ぬすむ 才真的是動詞。
    自動從釋義推，錯了不會報錯，只會讓學習者背下一個錯的詞性 ——
    比沒有標註更糟（跟振り仮名不能自動產生是同一個道理）。

    所以：**預設全是名詞，例外逐條列舉在下面**。
    這 549 個詞來自一本五十音入門書，本來就幾乎全是名詞；
    把少數例外寫死，比寫一套會猜錯的規則可靠得多。

【分類粒度為什麼是這幾種】
    以「對初學者有用」與「能讓干擾項更準」為準，不追求語言學完備：
      名詞／固有名詞／代名詞／数詞／い形容詞／な形容詞／動詞／表現
    固有名詞獨立出來是有實效的 —— 否則「大阪」會拿「蘋果」當干擾項。
    サ変名詞（散步、練習這類可以加 する 的）沒有另立一類：
    它們在這個階段就是當名詞用，多一類只會讓干擾項的池子變碎。
"""

# 預設之外的詞性。key 是日文原文（與資料的 ko 欄一致）。
EXCEPTIONS = {
    # ── い形容詞：語幹以 い 結尾且會活用 ────────────────────────
    'たのしい': 'い形容詞',
    'わるい': 'い形容詞',

    # ── な形容詞：外來語形容詞在日語裡走な形 ───────────────────
    'キュート': 'な形容詞',
    'ロマンティック': 'な形容詞',
    'ホット': 'な形容詞',      # ホットコーヒー。單獨也可當名詞用

    # ── 動詞 ────────────────────────────────────────────
    'ぬすむ': '動詞',
    'きて': '動詞',            # 來（て形）—— 促音課拿它跟 きって 做對比

    # ── 詞組與表現（item_type 已是 phrase，詞性再標一次是給干擾項用）──
    'ごはんを食べる': '動詞句',
    '野菜を買う': '動詞句',
    '水を飲む': '動詞句',
    '写真を撮る': '動詞句',
    'これをください': '表現',

    # ── 代名詞・数詞 ─────────────────────────────────────
    'わたし': '代名詞',
    'ろく': '数詞',

    # ── 固有名詞：地名・國名・節日・時代 ─────────────────────
    # 獨立成一類是為了干擾項：問「大阪」時拿「京都」「北海道」當選項才有意義，
    # 拿「蘋果」當選項等於送分。
    'おおさか': '固有名詞',
    'きょうと': '固有名詞',
    'にほん': '固有名詞',
    'ほっかいどう': '固有名詞',
    'ニューヨーク': '固有名詞',
    'イギリス': '固有名詞',
    'イタリア': '固有名詞',
    'インド': '固有名詞',
    'ヨーロッパ': '固有名詞',
    'ヨルダン': '固有名詞',
    'ユダヤ': '固有名詞',
    'クリスマス': '固有名詞',
    'ルネサンス': '固有名詞',
    'ヤクルト': '固有名詞',
}

DEFAULT = '名詞'

# 全部合法值。build.py 會據此擋住打錯字 ——
# 「動詞 」多一個空白會變成一個新的詞性，而它不會報錯，
# 只會讓那個詞永遠配不到同詞性的干擾項。
VALID = {DEFAULT, 'い形容詞', 'な形容詞', '動詞', '動詞句', '表現',
         '代名詞', '数詞', '固有名詞'}


def pos_for(ja, is_kana_card=False):
    """這個詞該掛什麼詞性。假名卡回空字串。

    假名卡（あ、ア…）不是單字，是字母。掛「名詞」會讓它跟 549 個名詞
    互為干擾項 —— 問「あ」時選項出現「蘋果」「桌子」，
    那不是在練假名，是在練排除法。
    """
    if is_kana_card:
        return ''
    return EXCEPTIONS.get(ja, DEFAULT)


def check_exceptions(all_ja):
    """例外表裡的詞如果已經不在資料裡，要說出來。

    改了某個詞的寫法卻忘了同步這張表，它會靜靜地失效 ——
    那個詞掉回預設的「名詞」，而畫面上看不出任何異狀。
    """
    missing = sorted(k for k in EXCEPTIONS if k not in all_ja)
    return [f"例外表有「{k}」（{EXCEPTIONS[k]}），但資料裡沒有這個詞" for k in missing]
